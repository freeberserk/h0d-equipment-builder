import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const m=JSON.parse(readFileSync(new URL("../module.json",import.meta.url),"utf8"));
assert.equal(m.id,"h0d-equipment-builder");
assert.equal(m.version,"0.2.3");
assert.ok(!Object.hasOwn(m.relationships,"modules"));
const dep=m.relationships.requires?.filter(x=>x.id==="h0d-template-manager");
assert.equal(dep?.length,1);
assert.equal(dep[0].type,"module");
assert.equal(dep[0].manifest,"https://github.com/freeberserk/h0d-template-manager/releases/latest/download/module.json");
assert.equal(dep[0].compatibility.minimum,"0.3.0");
assert.ok(m.relationships.systems?.some(s=>s.id==="custom-system-builder"&&s.type==="system"&&s.compatibility?.minimum==="6.0.2"));
console.log("OK: Equipment Builder dependency manifest.");
